import { Link } from "react-router-dom";
import { MetricReadout } from "../../components/MetricReadout";
import { StatusDot } from "../../components/StatusDot";
import { snapshot } from "../../content/snapshot";
import { workspace, newestRuns } from "../../content/workspace";

export default function Overview() {
  const c = snapshot.counts;
  const latest = newestRuns(workspace.runs).slice(0, 5);
  const stages = snapshot.stages;
  return (
    <div>
      <h1 className="text-4xl font-light">Research Overview</h1>
      <p className="mt-2 font-mono text-xs text-dim">
        SNAPSHOT {snapshot.generatedAt.replace("T", " ").slice(0, 16)} UTC — regenerated by scripts/web_snapshot.py
      </p>

      <div className="mt-8 grid grid-cols-2 gap-6 md:grid-cols-4">
        <MetricReadout label="Articles" value={String(c.articles)} />
        <MetricReadout label="Triaged" value={String(c.triaged)} />
        <MetricReadout label="Specs" value={String(c.specs)} />
        <MetricReadout label="Backtests" value={String(c.backtests + c.external)} />
      </div>

      <h2 className="mt-14 font-mono text-xs tracking-widest text-dim">PIPELINE</h2>
      <ol className="mt-4 border-t border-line">
        {stages.map((s) => (
          <li key={s.index} className="flex items-baseline justify-between border-b border-line py-3">
            <span className="text-sm">{s.index} · {s.name}</span>
            <span className="font-mono text-xs text-dim">{s.count ?? "—"} — {s.artifact}</span>
          </li>
        ))}
      </ol>

      <h2 className="mt-14 font-mono text-xs tracking-widest text-dim">LATEST RUNS</h2>
      {latest.length === 0 ? (
        <p className="mt-4 text-sm text-dim">No backtest runs yet.</p>
      ) : (
        <ol className="mt-4 border-t border-line">
          {latest.map((r, index) => (
            <li key={`${r.lane}-${r.slug}-${r.runAt ?? r.date}-${index}`} className="flex items-center gap-4 border-b border-line py-3">
              <StatusDot verdict={r.status} />
              <span className="min-w-0 flex-1 truncate font-mono text-sm">{r.slug}</span>
              <span className="font-mono text-xs text-dim">{r.date}</span>
            </li>
          ))}
        </ol>
      )}

      {workspace.failed.length > 0 && (
        <>
          <h2 className="mt-14 font-mono text-xs tracking-widest text-fail">RECENT FAILURES</h2>
          <ol className="mt-4 border-t border-line">
            {workspace.failed.slice(0, 5).map((f) => (
              <li key={f.slug} className="border-b border-line py-3">
                <span className="font-mono text-sm text-ink">{f.slug}</span>
                <p className="mt-1 line-clamp-2 font-mono text-[11px] text-dim">{f.error}</p>
              </li>
            ))}
          </ol>
        </>
      )}

      <p className="mt-10 text-sm text-dim">
        Every number comes from the repository's artifacts at snapshot time —
        nothing here is live or estimated.{" "}
        <Link to="/workspace/leaderboard" className="text-accent">Open the leaderboard →</Link>
      </p>
    </div>
  );
}
